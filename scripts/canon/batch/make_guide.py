def horn_pour(d, x0, y0, x1, y1, v):
    """task 606 — 머리 위로 기울여 붓는 짐승 뿔과 기름 줄기: 구역 위 왼쪽 넓은 밑동 → 아래 오른쪽 뾰족한 끝(구역 높이 0.7)으로 굽으며 가늘어지는 몸통 ·
    끝에서 구역 아래 끝(받는 이 머리 꼭대기)까지 가는 줄기. task 631 — 넓은 입으로 붓던 꼴을 뒤집음(사람 판정 620 「뿔 위아래 위치 바뀜」 = 넓은 입과
    뾰족한 끝의 자리가 바뀜 — 사전 oil-horn: 넓은 밑동을 쥐고 열린 뾰족한 끝으로 부음). 꼴 없이 문구만이면 기혼 다섯 판(601~605) 동안 뿔이 붓는 이 얼굴 높이에 세워지거나
    가로로 들려 입이 머리 옆·얼굴 앞(머리 위 0~5/8) — 배교 altar(task 546)처럼 자리를 기하로 준다."""
    w, h = x1 - x0, y1 - y0
    P0, C, P1 = (x0, y0), (x0 + w * 0.6, y0 + h * 0.1), (x0 + w * 0.85, y0 + h * 0.75)   # task 644: 비스듬히(약 45도) — 위 왼쪽 넓은 밑동에서 아래 오른쪽 뾰족한 끝. 631 b 세워 든 꼴(좁은 구역 수직)은 뿔이 똑바로 서거나 꺾인 관으로 그려짐(사람 639 「기름뿔 이상함」) · 가로로 누인 꼴은 넓은 입으로 부음(631 2/2)
